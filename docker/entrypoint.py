# -*- coding: utf-8 -*-
"""Container entrypoint: build a fresh v2 artifact into /data and serve it.

The image contains source code only.  Knowledge documents, the local embedding
model, the Chroma index, secrets and runtime outputs are mounted/created at
deploy time.  ``build_project`` is the same build path used locally; no host
absolute path or pre-existing ``outputs/`` directory is required.

Usage:
  python /usr/local/bin/rvs-entrypoint.py            # build (cached) + serve
  python /usr/local/bin/rvs-entrypoint.py --plan     # print resolved plan
  python /usr/local/bin/rvs-entrypoint.py --prepare  # build/config only
"""
from __future__ import annotations

import argparse
import contextlib
import hashlib
import json
import os
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

APP_ROOT = Path(os.getenv("RVS_APP_ROOT", "/app")).resolve()
DATA_ROOT = Path(os.getenv("RVS_DATA_ROOT", "/data")).resolve()
BIND_HOST = os.getenv("RVS_BIND_HOST", "0.0.0.0").strip() or "0.0.0.0"
PORT = int(os.getenv("RVS_PORT", "8000") or "8000")
ASSET_ROOT = Path(os.getenv("RVS_ASSETS_ROOT", "/assets")).resolve()

PROVIDER_KEYS = (
    "DEEPSEEK_API_KEY",
    "DASHSCOPE_API_KEY",
    "OPENAI_API_KEY",
    "ANTHROPIC_API_KEY",
)
SKIP_DIR_NAMES = {
    "__pycache__",
    ".pytest_cache",
    ".git",
    "node_modules",
    "assets",
    "outputs",
    "data",
    "logs",
    "sessions",
    "workspace",
}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def asset_bindings() -> dict[str, str]:
    """Explicit read-only asset locations inside the container."""
    return {
        "knowledge": str(
            Path(os.getenv("RVS_KNOWLEDGE_DIR", str(ASSET_ROOT / "knowledge"))).resolve()
        ),
        "models": str(
            Path(
                os.getenv(
                    "RVS_MODEL_DIR",
                    str(ASSET_ROOT / "models" / "bge-small-zh-v1.5"),
                )
            ).resolve()
        ),
        "rag_index": str(
            Path(os.getenv("RVS_RAG_INDEX_DIR", str(ASSET_ROOT / "rag_index"))).resolve()
        ),
    }


def source_fingerprint(app_root: Path = APP_ROOT) -> str:
    """Content fingerprint of the code/spec/frontend that affects the artifact."""
    digest = hashlib.sha256()
    roots = [
        app_root / "runtime",
        app_root / "robot_vacuum",
        app_root / "product_ui",
    ]
    for path in (app_root / "project.json", app_root / "requirements.txt"):
        if path.is_file():
            digest.update(b"file\0" + path.name.encode("utf-8") + b"\0")
            digest.update(path.read_bytes())
    for root in roots:
        if not root.is_dir():
            continue
        for current, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(
                name for name in dirnames if name not in SKIP_DIR_NAMES
            )
            for filename in sorted(filenames):
                if filename.endswith((".pyc", ".pyo")):
                    continue
                path = Path(current) / filename
                if not path.is_file():
                    continue
                relative = path.relative_to(app_root).as_posix()
                digest.update(b"file\0" + relative.encode("utf-8") + b"\0")
                digest.update(path.read_bytes())
    return digest.hexdigest()


def _atomic_write(target: Path, text: str, mode: int = 0o600) -> Path:
    """Write a small file via same-directory temp + fsync + replace.

    A container stop during startup must not leave a truncated instance config
    or a partially written credential file for the next start to consume.
    """
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(
        prefix=f".{target.name}.", suffix=".tmp", dir=str(target.parent)
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temp_name, mode)
        os.replace(temp_name, target)
    finally:
        with contextlib.suppress(OSError):
            os.unlink(temp_name)
    return target


def _write_env_file(target: Path) -> Path:
    """Write only provider credentials from the container environment.

    The file lives on the writable /data volume, never in the image or the
    artifact.  Empty deployments still get an empty 0600 file so health can
    report a clear missing-credential state instead of a path error.
    """
    lines = [
        "# Generated by the container entrypoint from the process environment.",
        "# Never commit or copy this file into an image/artifact.",
    ]
    for key in PROVIDER_KEYS:
        value = os.getenv(key, "")
        if value:
            if "\n" in value or "\r" in value:
                raise ValueError(f"provider credential {key} contains a newline")
            lines.append(f"{key}={value}")
    return _atomic_write(target, "\n".join(lines) + "\n", mode=0o600)


def _write_instance_config(artifact_root: Path, environment_file: Path) -> Path:
    manifest = json.loads((artifact_root / "manifest.json").read_text(encoding="utf-8"))
    entry = manifest.get("entry") if isinstance(manifest.get("entry"), dict) else {}
    config = {
        "schema_version": 1,
        "instance_id": os.getenv("RVS_INSTANCE_ID", "rvs-cloud"),
        "artifact_id": manifest.get("artifact_id"),
        "artifact_root": str(artifact_root),
        "name": os.getenv("RVS_INSTANCE_NAME", "扫地机器人售后客服"),
        "scenario": manifest.get("name") or "robot_vacuum",
        "version": manifest.get("version"),
        "workflow": entry.get("default_workflow") or "agent",
        "host": BIND_HOST,
        "port": PORT,
        "storage_root": str(DATA_ROOT / "runtime"),
        "environment_file": str(environment_file),
        "asset_bindings": asset_bindings(),
    }
    target = DATA_ROOT / "instance" / "instance.json"
    return _atomic_write(
        target,
        json.dumps(config, ensure_ascii=False, indent=2) + "\n",
        mode=0o600,
    )


def _load_cached(fingerprint: str) -> Path | None:
    marker = DATA_ROOT / "build" / "current.json"
    try:
        payload = json.loads(marker.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if payload.get("fingerprint") != fingerprint:
        return None
    bundle = Path(str(payload.get("bundle") or ""))
    if bundle.is_dir() and (bundle / "manifest.json").is_file() and (bundle / "serve.py").is_file():
        return bundle
    return None


def _build_artifact(fingerprint: str) -> Path:
    runtime_root = APP_ROOT / "runtime"
    if str(runtime_root) not in sys.path:
        sys.path.insert(0, str(runtime_root))
    from modules.artifacts.project import build_project  # noqa: PLC0415

    build_root = DATA_ROOT / "build" / "artifacts"
    build_root.mkdir(parents=True, exist_ok=True)
    print(f"[entrypoint] building artifact from {APP_ROOT} -> {build_root}", flush=True)
    result = build_project(APP_ROOT, build_root, include_assets=False)
    bundle = Path(str(result["bundle"])).resolve()
    marker = DATA_ROOT / "build" / "current.json"
    _atomic_write(
        marker,
        json.dumps(
            {
                "fingerprint": fingerprint,
                "bundle": str(bundle),
                "artifact_id": result["manifest"].get("artifact_id"),
                "built_at": _now(),
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        mode=0o644,
    )
    print(f"[entrypoint] built {bundle}", flush=True)
    return bundle


def prepare() -> tuple[Path, Path]:
    fingerprint = source_fingerprint(APP_ROOT)
    bundle = _load_cached(fingerprint)
    if bundle is None:
        bundle = _build_artifact(fingerprint)
    env_file = _write_env_file(DATA_ROOT / "instance" / "runtime.env")
    config_path = _write_instance_config(bundle, env_file)
    return bundle, config_path


def plan() -> dict[str, Any]:
    fingerprint = source_fingerprint(APP_ROOT)
    return {
        "app_root": str(APP_ROOT),
        "data_root": str(DATA_ROOT),
        "asset_bindings": asset_bindings(),
        "bind": f"{BIND_HOST}:{PORT}",
        "source_fingerprint": fingerprint,
        "cached": _load_cached(fingerprint) is not None,
        "serve_static": os.getenv("RVS_SERVE_STATIC", "true"),
        "admin_token_configured": bool(os.getenv("RVS_ADMIN_TOKEN", "").strip()),
        "access_token_configured": bool(os.getenv("RVS_ACCESS_TOKEN", "").strip()),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build and serve the container artifact")
    parser.add_argument("--plan", action="store_true", help="print resolved paths and exit")
    parser.add_argument("--prepare", action="store_true", help="build/config only, do not serve")
    args = parser.parse_args(argv)

    if args.plan:
        print(json.dumps(plan(), ensure_ascii=False, indent=2))
        return 0

    if not (APP_ROOT / "project.json").is_file():
        print(f"[entrypoint] project.json not found under {APP_ROOT}", file=sys.stderr)
        return 2
    bundle, config_path = prepare()
    if args.prepare:
        print(f"[entrypoint] prepared {config_path}", flush=True)
        return 0
    entry = bundle / "serve.py"
    if not entry.is_file():
        print(f"[entrypoint] serve.py missing in {bundle}", file=sys.stderr)
        return 2
    print(f"[entrypoint] serving {bundle} on {BIND_HOST}:{PORT}", flush=True)
    # Replace PID 1 so uvicorn receives container stop signals directly.
    os.execv(
        sys.executable,
        [
            sys.executable,
            str(entry),
            "--instance-config",
            str(config_path),
            "--host",
            BIND_HOST,
            "--port",
            str(PORT),
        ],
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
